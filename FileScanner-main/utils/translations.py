def get_text(key: str, language: str = "es") -> str:
    """Obtiene el texto traducido para la clave dada"""
    return TRANSLATIONS.get(language, TRANSLATIONS["es"]).get(key, key)

def get_available_languages() -> list:
    """Retorna la lista de idiomas disponibles"""
    return list(TRANSLATIONS.keys())

